const es = Object.fromEntries(Object.keys(en).map((key) => [key, key]))
const enToEs = Object.fromEntries(Object.entries(en).map(([spanish, english]) => [english, spanish]))
export const messages = { es, en }

export function setLanguage(value) {
  language.value = value === 'en' ? 'en' : 'es'
  try { localStorage.setItem(LANGUAGE_KEY, language.value) } catch { /* storage unavailable */ }
  if (typeof document !== 'undefined') document.documentElement.lang = language.value === 'en' ? 'en' : 'es'
}

const spanishAliases = {
  'Subir Archivo': 'Subir archivo',
  'Camara local': 'Cámara Local',
  'Camara URL': 'Cámara URL',
  'Cámara local': 'Cámara Local',
}

export function t(value) {
  if (value === null || value === undefined) return value
  const rawKey = String(value)
  const key = spanishAliases[rawKey] ?? rawKey
  if (language.value === 'es') return enToEs[key] ?? key
  if (en[key]) return en[key]

  const dynamic = [
    [/^Datos de (.+) ya están cargados\.$/, 'Data for $1 is already loaded.'],
    [/^Datos de (.+) cargados para actualizar\.$/, 'Data for $1 loaded for update.'],
    [/^Datos de (.+) cargados\.$/, 'Data for $1 loaded.'],
    [/^La placa (.+) ya existe en el listado\. ¿Desea actualizarla\?$/, 'Plate $1 already exists in the list. Do you want to update it?'],
    [/^Editando el usuario (.+)\. Puede actualizar el nombre y el rol o restablecer su contraseña\.$/, 'Editing user $1. You can update the name and role or reset the password.'],
    [/^¿Restablecer la contraseña de (.+)\?$/, 'Reset the password for $1?'],
    [/^No se pudo completar la operación: (.*)$/, 'Could not complete the operation: $1'],
    [/^Camión (.+) registrado y autorizado por (.+)\.$/, 'Truck $1 registered and authorized by $2.'],
    [/^Camión (.+) registrado, pendiente de autorización\.$/, 'Truck $1 registered, pending authorization.'],
    [/^(\d+) camión\(es\) actualizado\(s\): (.+)\.$/, '$1 truck(s) updated: $2.'],
    [/^(\d+) operaciones de demostración creadas\.$/, '$1 demo operation(s) created.'],
    [/^(\d+) operaciones de demostración borradas\.$/, '$1 demo operation(s) deleted.'],
    [/^Proceso terminado: se generaron (\d+) operación\(es\) de demostración\.$/, 'Process complete: $1 demo operation(s) generated.'],
    [/^Proceso terminado: se borraron (\d+) operación\(es\) DEMO\.$/, 'Process complete: $1 DEMO operation(s) deleted.'],
    [/^No se pudo guardar el camión\.$/, 'Could not save the truck.'],
    [/^Confirmando la misma placa: (\d+)\/2 cuadros$/, 'Confirming the same plate: $1/2 frames'],
    [/^La placa (.+) ya existe en el listado\. ¿Desea actualizarla\?$/, 'Plate $1 already exists in the list. Do you want to update it?'],
    [/^Autorización de (.+) actualizada en la lista (.+)\.$/, 'Authorization for $1 updated on the $2 list.'],
    [/^La placa (.+) quedó sin autorización\.$/, 'Plate $1 no longer has authorization.'],
    [/^Garita (.+) agregada\.$/, 'Checkpoint $1 added.'],
    [/^\d+ garita\(s\) actualizada\(s\)\.$/, key => key.replace('garita(s) actualizada(s)', 'checkpoint(s) updated')],
    [/^La placa (.+) ahora está en la lista (.+)\.$/, 'Plate $1 is now on the $2 list.'],
    [/^Solo se pueden cambiar camiones registrados\. Revise: (.+)$/, 'Only registered trucks can be changed. Check: $1'],
    [/^No se pudo actualizar la autorización: (.+)$/, 'Could not update authorization: $1'],
    [/^\d+ usuario\(s\) actualizado\(s\)\.$/, key => key.replace('usuario(s) actualizado(s)', 'user(s) updated')],
    [/^Camión (.+) quedó sin autorización\.$/, 'Truck $1 no longer has authorization.'],
    [/^Garita (.+) agregada\.$/, 'Checkpoint $1 added.'],
    [/^No se pudo registrar: (.+)$/, 'Could not record: $1'],
    [/^Complete los campos obligatorios: (.+)$/, 'Complete the required fields: $1'],
    [/^El camión (.+) quedó sin autorización\.$/, 'Truck $1 no longer has authorization.'],
    [/^La placa (.+) ahora está en la lista (.+)\.$/, 'Plate $1 is now on the $2 list.'],
    [/^Autorización de (.+) actualizada en la lista (.+)\.$/, 'Authorization for $1 updated on the $2 list.'],
  ]
  for (const [pattern, replacement] of dynamic) {
    if (pattern.test(key)) return key.replace(pattern, replacement)
  }
  return key
}

export function installI18n(app) {
  app.config.globalProperties.$t = t
  document.documentElement.lang = language.value === 'en' ? 'en' : 'es'
}
